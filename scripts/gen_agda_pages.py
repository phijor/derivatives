import mkdocs_gen_files

from pathlib import Path
import os
from typing import TextIO


def main():
    html_source_dir = get_html_source_dir()

    print("Copying hightlighted Markdown files...")
    for md in html_source_dir.glob("*.md"):
        prepare_md(md)

    print("Wrapping raw HTML files as Markdown...")
    for html in html_source_dir.glob("*.html"):
        prepare_html(html)


def get_html_source_dir() -> Path:
    dir = os.environ.get("AGDA_HTML_DIR")
    if dir is not None:
        print(f"Overriding HTML source directory: AGDA_HTML_DIR={dir}")
        return Path(dir)
    else:
        return Path("html")


def prepare_md(md: Path):
    print(f"Markdown: '{md}'")
    if not md.is_file():
        print(f"!!! '{md}' is not a regular file")
        return

    target: TextIO
    with mkdocs_gen_files.open(md.name, "w+", encoding="utf-8") as target:
        content = md.read_text(encoding="utf-8")
        for patch in [retarget_readme_links, exclude_agda_blocks_from_search]:
            content = patch(content)
        target.write(content)


def prepare_html(html: Path):
    print(f"HTML: '{html}'")

    if not html.is_file():
        print(f"!!! '{html}' is not a regular file")
        return

    target_name = f"{html.stem}.md"
    with mkdocs_gen_files.open(target_name, "w+", encoding="utf-8") as target:
        # See `exclude_agda_blocks_from_search` for why `data-search-exclude` is necessary.
        target.write('<pre class="Agda" data-search-exclude>\n')
        target.write(retarget_readme_links(html.read_text(encoding="utf-8")))
        target.write("</pre>\n")


def retarget_readme_links(content: str) -> str:
    # Agda names each module's page after the module, so the `README` module
    # links to itself -- and is linked to -- as `README.html`.  MkDocs, however,
    # treats `README.md` as a directory index and renders it as `index.html`,
    # so every one of those links points at a page that is never written.
    #
    # Retarget them at the page that is actually produced.  Anchors are preserved,
    # as Agda's `id` attributes survive into the rendered page unchanged.
    #
    # Matching on the opening quote keeps this from touching a module whose
    # name merely ends in `README`, such as `Foo.README.html`.
    return content.replace('href="README.html', 'href="index.html')


def exclude_agda_blocks_from_search(content: str) -> str:
    # The `mkdocs-material` search plugin will attempt to add the content
    # of all code blocks to the search index.  This only adds noise to the
    # search results:  The code blocks are huge, and show up as a single
    # entry in the search results, completely drowning out any individual
    # matches.  Therefore, we exclude all Agda code blocks from indexing.
    #
    # In a later pass (`merge_search_index.py`), we use a search index
    # generated by a custom Agda backend (blindhuhn) to add entries for
    # for all definitions found in such code blocks.  This makes search
    # results less noisy (smaller matching spans) and more accurate
    # (only actual text paragraphs and individual Agda definitions are indexed).
    return content.replace(
        '<pre class="Agda">', '<pre class="Agda" data-search-exclude>'
    )


main()
