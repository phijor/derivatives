"""Fail the build if a generated page links to a file the site does not contain.

Usage: check_internal_links.py [SITE_DIR]

MkDocs rewrites the URLs of some files (namely, `README.lagda.md` turns into `index.html`,
not `README.html`).  This script ensures that all relative links of HTML files inside of
SITE_DIR resolve against existing files.
"""

import re
import sys
from pathlib import Path
from urllib.parse import unquote

# `404.html` is the missing page fall back, which is served from any depth.
# Instead of trying to understand how relative links should resolve, just
# exclude it.  It is generated by the theme and likely to be correct.
EXEMPT = {"404.html"}

LINK = re.compile(r'(?:href|src)="([^"]+)"')

# Absolute URLs, protocol-relative URLs and same-page fragments.
EXTERNAL = re.compile(r"^(?:[A-Za-z][A-Za-z0-9+.-]*:|//|#)")


def main() -> int:
    site = Path(sys.argv[1] if len(sys.argv) > 1 else "site")
    if not site.is_dir():
        print(f"!!! '{site}' is not a directory", file=sys.stderr)
        return 1

    dangling: dict[str, set[Path]] = {}
    checked = 0

    for page in sorted(site.rglob("*.html")):
        if page.name in EXEMPT:
            continue
        checked += 1
        for ref in LINK.findall(page.read_text(encoding="utf-8")):
            if EXTERNAL.match(ref):
                continue
            # Strip the fragment and query; percent-decode what remains, as
            # Agda escapes non-ASCII identifiers in its link targets.
            target = unquote(ref.split("#")[0].split("?")[0])
            if target and not (page.parent / target).exists():
                dangling.setdefault(target, set()).add(page)

    if dangling:
        print(f"{len(dangling)} link target(s) missing from the site:", file=sys.stderr)
        for target, sources in sorted(dangling.items()):
            example = sorted(sources)[0]
            print(
                f"  {target}  <- {len(sources)} page(s), e.g. {example}",
                file=sys.stderr,
            )
        return 1

    print(f"Checked internal links on {checked} page(s): none dangling.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
